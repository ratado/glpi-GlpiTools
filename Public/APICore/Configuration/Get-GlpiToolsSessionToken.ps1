<#
.SYNOPSIS
    Get GLPI Session Token.
.DESCRIPTION
    This function getting session token generated by initSession.
.EXAMPLE
    PS C:\Users\Wojtek> Get-GlpiToolsSessionToken
    Running script like that, shows you the current session token.
.INPUTS
    None
.OUTPUTS
    String or null
.NOTES
    PSP 12/2018
#>

function Get-GlpiToolsSessionToken {
    [CmdletBinding()]
    param (
        
    )
    
    begin {


    }
    
    process {

        # API v3: the access token expires, so it is renewed (or requested) when needed
        if ((Get-GlpiToolsApiVersion) -eq 'v3') {
            $Current = $global:GlpiToolsSessionToken
            if ($null -eq $Current -or ($Current.ExpiresAt -and [datetime]::UtcNow -ge $Current.ExpiresAt)) {
                Update-GlpiToolsAccessToken
            }
            else {
                $Current
            }
            return
        }

        if($global:GlpiToolsSessionToken -eq $null){
			Set-GlpiToolsInitSession
		}
		else {
			$global:GlpiToolsSessionToken
		}
    }
    
    end {
		
    }
}